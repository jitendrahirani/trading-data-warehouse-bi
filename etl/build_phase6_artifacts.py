"""Phase 6: generate the Tabular Editor scripts and the measure catalog from bi/etl/semantic_model.py.

    bi_env python bi/etl/build_phase6_artifacts.py
Writes bi/powerbi/add_measures.csx, bi/powerbi/tidy_model.csx and bi/docs/Phase6_Measure_Catalog.xlsx (with the SQL value
of every measure for its 3 validation cases, computed now from TradingBI_Dev).
"""
from __future__ import annotations

import sys
from datetime import datetime
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font

import apply_ddl
import db
import semantic_model as sm

BI = Path(__file__).resolve().parents[1]
PBI = BI / "powerbi"


def cs(s: str) -> str:
    """C# verbatim string literal."""
    return '@"' + s.replace('"', '""') + '"'


def add_measures_csx() -> str:
    lines = [
        "// Phase 6: adds every measure of bi/etl/semantic_model.py that the _Measures table does not have yet.",
        "// GENERATED by bi/etl/build_phase6_artifacts.py - do not edit by hand.",
        "// Run in Tabular Editor 2 opened from Power BI Desktop (External Tools > Tabular Editor) > C# Script > Run (F5),",
        "// then File > Save (Ctrl+S) to write the measures back into Power BI Desktop.",
        "if (!Model.Tables.Contains(\"_Measures\")) { Error(\"Create the _Measures table first (build guide, Part C step 1).\"); return; }",
        "if (!Model.Tables.Contains(\"Threshold\")) { Error(\"Create the Threshold what-if parameter first (build guide, Part C step 4).\"); return; }",
        "var t = Model.Tables[\"_Measures\"];",
        "var added = new System.Collections.Generic.List<string>();",
        "var kept = new System.Collections.Generic.List<string>();",
        "System.Action<string, string, string, string, string> add = (name, folder, fmt, desc, expr) => {",
        "    if (t.Measures.Contains(name)) { kept.Add(name); return; }",
        "    var m = t.AddMeasure(name, expr, folder);",
        "    if (fmt != \"\") m.FormatString = fmt;",
        "    m.Description = desc;",
        "    added.Add(name);",
        "};",
    ]
    for m in sm.MEASURES:
        desc = m.desc + (f" ({m.kpi})" if m.kpi else "")
        lines.append(f"add({cs(m.name)}, {cs(m.folder)}, {cs(m.fmt)}, {cs(desc)},\n    {cs(m.dax)});")
    lines += ["Info(\"Added \" + added.Count + \" measures. Already there (typed by you, left unchanged): \" + string.Join(\", \", kept));"]
    return "\n".join(lines) + "\n"


def tidy_model_csx() -> str:
    sort_lines = "\n".join(
        f"sortBy({cs(t)}, {cs(c)}, {cs(by)});" for t, c, by in sm.SORT_BY)
    return f"""// Phase 6: tidy the model - hide technical columns, set sort-by columns, stop Power BI summing numbers that are not amounts.
// GENERATED by bi/etl/build_phase6_artifacts.py. Run in Tabular Editor 2 (from Power BI Desktop), then Ctrl+S.
int hidden = 0, sorted = 0, nosum = 0;
foreach (var tb in Model.Tables) {{
    foreach (var c in tb.Columns) {{
        bool key = c.Name.EndsWith("Key") || (c.Name == "EtlRunId" && tb.Name != "EtlRun");
        if (key && !c.IsHidden) {{ c.IsHidden = true; hidden++; }}
        bool isAmount = c.DataType == DataType.Decimal || c.DataType == DataType.Double;
        bool isFact = tb.Name.StartsWith("DQ") || tb.Name.StartsWith("Model") || tb.Name == "Trade" || tb.Name.StartsWith("Feature")
                      || tb.Name.StartsWith("Etl") || tb.Name == "Reconciliation";
        if (c.DataType == DataType.Int64 && (!isFact || key || c.Name.EndsWith("Id") || c.Name.EndsWith("No") || c.Name == "Rank")
            && c.SummarizeBy != AggregateFunction.None) {{ c.SummarizeBy = AggregateFunction.None; nosum++; }}
    }}
}}
System.Action<string, string, string> sortBy = (table, col, by) => {{
    if (!Model.Tables.Contains(table)) return;
    var tb = Model.Tables[table];
    if (tb.Columns.Contains(col) && tb.Columns.Contains(by)) {{ tb.Columns[col].SortByColumn = tb.Columns[by]; sorted++; }}
}};
{sort_lines}
if (Model.Tables.Contains("UserDesk")) Model.Tables["UserDesk"].IsHidden = true;
Info("Hidden " + hidden + " key columns; " + sorted + " sort-by columns set; " + nosum + " columns set to 'Don't summarize'.");
"""


def catalog(conn) -> None:
    wb = Workbook()
    ws = wb.active
    ws.title = "Read me"
    lines = [
        ("Phase 6: measure catalog and validation plan", apply_ddl.TITLE),
        (f"Generated {datetime.now():%Y-%m-%d %H:%M} from bi/etl/semantic_model.py. Do not edit by hand.", apply_ddl.NOTE),
        ("", apply_ddl.BODY),
        (f"{len(sm.MEASURES)} measures in 5 display folders. 'By hand' = you type it yourself in Power BI Desktop (Part C of the build guide); "
         "the rest are added by bi/powerbi/add_measures.csx in Tabular Editor.", apply_ddl.BODY),
        ("Validation: every measure is checked for 3 filter combinations of its family. 'SQL value now' is what the same calculation on the "
         "rpt views returns today. After you build the model, bi/etl/validate_measures.py runs the DAX query of each row in YOUR open "
         "Power BI model and compares it with the SQL (recomputed at that moment).", apply_ddl.BODY),
        ("Tables: load these 24 views and rename each query to the table name shown (Tables sheet).", apply_ddl.BODY),
    ]
    for i, (text, font) in enumerate(lines, 1):
        c = ws.cell(row=i, column=1, value=text)
        c.font, c.alignment = font, Alignment(wrap_text=True, vertical="top")
    ws.column_dimensions["A"].width = 140

    meas = pd.DataFrame([{"#": i, "measure": m.name, "folder": m.folder, "by hand": "yes" if m.hand else "", "KPI": m.kpi,
                          "format": m.fmt, "description": m.desc, "DAX": m.dax} for i, m in enumerate(sm.MEASURES, 1)])
    apply_ddl._write(wb.create_sheet("Measures"), "Measures", "Display folder = where the measure appears in the Data pane.", meas,
                     {"#": 5, "measure": 26, "folder": 16, "by hand": 8, "KPI": 6, "format": 14, "description": 50, "DAX": 100})

    rows = []
    for m in sm.MEASURES:
        for k, f in enumerate(sm.cases_for(m), 1):
            sql = sm.measure_sql(m, f)
            try:
                r = conn.cursor().execute(sql).fetchone()
                v = None if r is None else r[0]
                v = float(v) if isinstance(v, (int, float)) or type(v).__name__ == "Decimal" else (None if v is None else str(v))
            except Exception as e:                       # noqa: BLE001
                v = f"SQL ERROR {e}"
            rows.append({"measure": m.name, "case": k,
                         "filters": "; ".join(f"{t}[{c}] = {val}" for t, c, val in f) or "(no filter)",
                         "SQL value now": v, "DAX query": sm.dax_query(m, f), "SQL": " ".join(sql.split())})
    val = pd.DataFrame(rows)
    apply_ddl._write(wb.create_sheet("Validation cases"), "Validation cases (3 per measure)",
                     "validate_measures.py runs the DAX query in your model and compares it with the SQL.", val,
                     {"measure": 26, "case": 6, "filters": 50, "SQL value now": 18, "DAX query": 70, "SQL": 90})

    tables = pd.DataFrame([{"table name in the model": t, "source view": v,
                            "kind": "dimension" if t in sm.ALIAS or t in ("Time", "GateClass", "ActualClass", "PredictedClass") else
                            ("security (hidden)" if t == "UserDesk" else "fact")} for t, v in sm.TABLES.items()])
    apply_ddl._write(wb.create_sheet("Tables"), "Tables", "Rename every query to the table name (right-click the query > Rename).", tables,
                     {"table name in the model": 24, "source view": 24, "kind": 18})
    import check_model                                     # live status of YOUR open model, when there is one
    model = check_model.read_model()
    if model is not None:
        rel = pd.DataFrame(check_model.relationship_status(model))
        order = {"MISSING": 0, "FIX": 1, "EXTRA (not in the design)": 2, "OK (already there)": 3}
        rel = rel.assign(_o=rel["in your model now"].map(order), _a=rel["active"].ne("yes")).sort_values(["_o", "_a", "from (many)"]).drop(columns=["_o", "_a"])   # active before inactive: create Exit before Entry
        rel["Done?"] = None
        n_todo = int((~rel["in your model now"].str.startswith("OK")).sum())
        note = (f"Status read from your open Power BI model at {datetime.now():%Y-%m-%d %H:%M}: {n_todo} to do (top rows), "
                f"{len(rel) - n_todo} already correct. Every relationship: Many to one (*:1), cross-filter Single.")
    else:
        rel = pd.DataFrame([{"from (many)": f"{a}[{b}]", "to (one)": f"{c}[{d}]", "active": "yes" if act else "NO (inactive)",
                             "in your model now": "(model not open)", "what to do": "Create: Many to one, Single", "Done?": None}
                            for a, b, c, d, act in sm.RELATIONSHIPS])
        note = "All many-to-one, single direction. UserDesk has no relationship."
    ws_rel = wb.create_sheet("Relationships")
    apply_ddl._write(ws_rel, f"Relationships: the {len(sm.RELATIONSHIPS)} in the design", note, rel,
                     {"from (many)": 32, "to (one)": 24, "active": 14, "in your model now": 22, "what to do": 64, "Done?": 9})
    from openpyxl.styles import PatternFill
    from openpyxl.worksheet.datavalidation import DataValidation
    status_fill = {"MISSING": "F8CBAD", "FIX": "FFE699", "EXTRA": "F8CBAD", "OK": "C6EFCE"}
    done_col = list(rel.columns).index("Done?") + 1
    st_col = list(rel.columns).index("in your model now") + 1
    dv = DataValidation(type="list", formula1='"Yes,No"', allow_blank=True)
    ws_rel.add_data_validation(dv)
    for i in range(5, 5 + len(rel)):
        st = str(ws_rel.cell(row=i, column=st_col).value or "")
        fill = next((v for k, v in status_fill.items() if st.startswith(k)), None)
        if fill:
            ws_rel.cell(row=i, column=st_col).fill = PatternFill("solid", fgColor=fill)
        ws_rel.cell(row=i, column=done_col).fill = PatternFill("solid", fgColor="FFF2CC")
        dv.add(ws_rel.cell(row=i, column=done_col))
    rls = pd.DataFrame([{"role": r, "table": t, "DAX filter": e} for r, t, e in sm.RLS_ROLES])
    apply_ddl._write(wb.create_sheet("RLS roles"), "Row-level security roles", "Modeling > Manage roles. Test users are in sec.UserInstrument.", rls,
                     {"role": 18, "table": 12, "DAX filter": 110})
    out = BI / "docs" / "Phase6_Measure_Catalog.xlsx"
    wb.save(out)
    errors = int(val["SQL value now"].astype(str).str.startswith("SQL ERROR").sum())
    print(f"wrote {out.relative_to(BI.parent)}: {len(meas)} measures, {len(val)} validation cases, SQL errors: {errors}")


def main() -> int:
    PBI.mkdir(exist_ok=True)
    (PBI / "add_measures.csx").write_text(add_measures_csx(), encoding="utf-8")
    (PBI / "tidy_model.csx").write_text(tidy_model_csx(), encoding="utf-8")
    print("wrote bi/powerbi/add_measures.csx and tidy_model.csx")
    catalog(db.connect("dev", autocommit=True))
    return 0


if __name__ == "__main__":
    sys.exit(main())
